from collections import deque

def solution(maps):
    # 맵의 행(n)과 열(m) 크기를 가져옵니다.
    n = len(maps)
    m = len(maps[0])
    
    # 큐(Queue) 생성
    # 큐에는 (x좌표, y좌표, 현재까지의 비용)을 튜플로 저장합니다.
    q = deque()
    
    # 1. 시작점 (0, 0)을 큐에 추가하고, 비용은 1로 시작합니다.
    q.append((0, 0, 1))
    
    # 2. 방문 처리: 시작점을 큐에 넣자마자 '방문함'(벽)으로 표시합니다.
    #    (maps[0][0] = 0)
    #    이렇게 해야 다시 시작점으로 돌아오는 무한 루프를 막을 수 있습니다.
    maps[0][0] = 0
    
    # 상, 하, 좌, 우 4방향을 탐색하기 위한 dx, dy 리스트
    dx = [-1, 1, 0, 0] # 행(x) 이동 (상, 하)
    dy = [0, 0, -1, 1] # 열(y) 이동 (좌, 우)
    
    # 3. 큐가 빌 때까지 반복합니다.
    while q:
        # 큐에서 현재 위치(x, y)와 비용(cost)을 꺼냅니다.
        x, y, cost = q.popleft()
        
        # 4. 목적지 도달 확인
        # 현재 위치가 (n-1, m-1)인지 확인합니다.
        if x == n - 1 and y == m - 1:
            # BFS는 항상 최단 거리를 먼저 찾으므로,
            # 목적지에 도착하는 순간의 cost가 정답입니다.
            return cost
        
        # 5. 4방향 탐색
        for i in range(4):
            nx = x + dx[i] # 다음 x 위치
            ny = y + dy[i] # 다음 y 위치
            
            # (nx, ny)가 맵 범위(0 <= nx < n, 0 <= ny < m) 안에 있는지 확인
            if 0 <= nx < n and 0 <= ny < m:
                
                # (nx, ny)가 벽이 아닌 길(1)인지 확인
                # (이미 방문한 곳은 0이므로, 1인지 확인하는 것만으로
                #  '방문하지 않은 길'인지 검사 가능)
                if maps[nx][ny] == 1:
                    
                    # 6. 방문 처리 및 큐에 추가
                    # (nx, ny)를 방문했다고 표시 (0으로 만듦)
                    maps[nx][ny] = 0 
                    # 큐에 다음 위치와 (현재 비용 + 1)을 추가
                    q.append((nx, ny, cost + 1))
                    
    # 7. 도달 불가 처리
    # while 루프가 끝날 때까지 (큐가 다 빌 때까지)
    # 목적지에 도달하지 못했다면, 길이 없는 것입니다.
    return -1